def build_items():
 result=[]
 for n,(cat,name,price,description) in enumerate(ROWS):
  groups=[]
  if cat=='limonady': groups=[f'volume-{n}']
  if cat=='napitki': groups=[f'bottle-{n}']
  if name=='Гонконгские вафли': groups=['topping','sprinkles']
  result.append(dict(category_slug=cat,name=name,price=price,description=description,sort_order=n,
   available=price is not None,is_combo=name in ('Орбита Чикен','Орбита Биф'),mod_groups=groups,
   weight='30 см' if cat=='pizza-30' else '0,5 л' if cat=='molochnye-kokteyli' else '',
   sales_department='kitchen' if cat in ('ufo','pizza-30','zakuski') else 'bar'))
 return result

def build_modifier_groups():
 result=[]
 for item in build_items():
  cat=item['category_slug'];keys=item['mod_groups']
  if cat not in ('limonady','napitki'):continue
  delta=300 if item['name'] in ('Киви-лайм','Матча') else 200
  result.append(dict(key=keys[0],name='Объём',type='single',is_required=True,min_select=1,max_select=1,
   options=[dict(name='0,5 л',price=0),dict(name='0,65 л' if cat=='limonady' else '1 л',price=delta if cat=='limonady' else 0)]))
 for key,name,options in [('topping','Топинг',['клубничный','шоколадный','киви']),('sprinkles','Посыпка',['орехи','кокосовая стружка','шоколадная посыпка','Oreo'])]:
  result.append(dict(key=key,name=name,type='single',is_required=False,min_select=0,max_select=1,options=[dict(name=x,price=0) for x in options]))
 return result

def verify_catalog():
 items=build_items()
 return dict(categories_total=8,categories_visible=8,items_total=len(items),items_visible=len(items),items_expected_visible=37,items_expected_total=37,
  modifier_groups=len(build_modifier_groups()),items_by_category={c[0]:sum(x['category_slug']==c[0] for x in items) for c in CATEGORIES},
  prices_pending=[x['name'] for x in items if x['price'] is None])
