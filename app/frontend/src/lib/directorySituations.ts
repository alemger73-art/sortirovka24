/** Search that understands everyday words: «вода» finds Қарағанды Су, «свет» — Қарағанды Жарық. */
const SYNONYMS: [RegExp, string[]][] = [
  [/^(вод|су$|канализ|кран)/, ['су', 'вод', 'канализ']],
  [/^(свет|электр|жарық|жарык)/, ['жарық', 'электр', 'свет']],
  [/^(тепл|отопл|батаре|жылу|горяч)/, ['тепл', 'отопл', 'жылу']],
  [/^(газ)/, ['газ', 'alemgaz']],
  [/^(мусор|қоқыс|кокыс|контейнер)/, ['мусор', 'экоалем', 'таза', 'қоқыс']],
  [/^(врач|доктор|поликл|больниц|емхан|анализ)/, ['поликлин', 'медицин', 'больниц', 'анализ', 'олимп']],
  [/^(полиц|участков|милиц)/, ['полиц', 'участков']],
  [/^(школ|мектеп)/, ['школ', 'мектеп']],
  [/^(сад|садик|балабақ|ясли)/, ['сад', 'балабақ', 'ясли']],
  [/^(почт|посылк|пошта)/, ['qazpost', 'почт']],
  [/^(интернет|вайфай|wifi|тв$|телевид)/, ['интернет', 'телевид', 'телеком']],
  [/^(аким|әкім)/, ['аким', 'әкім']],
  [/^(аптек|лекарств|дәріхана)/, ['аптек']],
  [/^(цон|госуслуг|егов|egov|хқко)/, ['цон', 'госуслуг', '1414', 'egov']],
];
export function smartMatch(text: string, query: string): boolean {
  const norm = (v: string) => v.toLocaleLowerCase().replace(/ё/g, 'е');
  const hay = norm(text);
  const words = norm(query).split(/\s+/).filter(Boolean);
  if (!words.length) return true;
  return words.every((w) => {
    if (/^[+\d()–-]+$/.test(w)) return hay.replace(/\D/g, '').includes(w.replace(/\D/g, ''));
    if (hay.includes(w)) return true;
    const syn = SYNONYMS.find(([re]) => re.test(w));
    return !!syn && syn[1].some((s) => hay.includes(s));
  });
}

