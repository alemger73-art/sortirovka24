export function useStoreTranslations() {
  const { lang } = useLanguage();
  return useCallback((source: string, values: readonly (string | number)[] = []): string => {
    const template = lang === 'kz' ? (storeTranslations[source] ?? source) : source;
    return template.replace(/\{(\d+)\}/g, (match, index: string) => String(values[Number(index)] ?? match));
  }, [lang]);
}

/** Localize generated guard copy while preserving API and customer-provided messages. */
export function storeCheckoutBlockReason(ctx: FoodCheckoutContext, st: ReturnType<typeof useStoreTranslations>): string | null {
  const reason = foodCheckoutBlockReason(ctx);
  if (!reason) return null;
  if (!ctx.kitchenOpen) return ctx.kitchenMessage || st('Сейчас кухня закрыта');
  if (ctx.minOrder > 0 && ctx.cartTotal < ctx.minOrder) {
    return st('Минимальная сумма заказа — {0} ₸', [ctx.minOrder.toLocaleString('ru-RU')]);
  }
  if (reason === ctx.deliveryQuoteError || reason === ctx.deliveryUnavailableMessage) return reason;
  return st(reason);
}
